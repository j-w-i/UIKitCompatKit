import UIKit

/// Autoresizing-mask -> legacy constraint translation (explicit-constraint form).
///
/// The real `NSAutoresizingMaskLayoutConstraint` equations are generated by `LegacyLayoutEngine` from
/// the item's `layoutAutoresizingMask` plus its captured `layoutAutoresizingReference` (per-mask
/// equations, proportional flexible margins, regeneration on superview resize; semantics §3.1). The
/// bridge exposes that geometry through the `LegacyLayoutItem` conformance; this helper is the simpler
/// RRAutoLayout-compatible constraint form for callers that want concrete `RRLayoutConstraint` objects
/// (nib/ObjC `addConstraint:` flow, diagnostics, tests):
///
///     view.left   == superview.left   + frame.minX
///     view.top    == superview.top    + frame.minY
///     view.width  == frame.width
///     view.height == frame.height
///
/// all at required priority. The autoresizing mask is accepted for API fidelity (it is what old code
/// configures) and is recorded in the constraint identifiers, but the current frame stays the numeric
/// authority for this explicit form.
///
/// UIKit rejects a *location* attribute with no second item ("location equal to a constant" is an
/// `NSInvalidArgumentException`), so a view without a superview only gets the width/height form here;
/// position is only meaningful relative to a container.
public enum LegacyAutoLayoutAutoresizing {

    /// The four frame-pinning constraints for `view`, in superview coordinates.
    ///
    /// - Parameter view: the view whose frame should be pinned. Its current `frame` (in its superview's
    ///   coordinate space) is used verbatim.
    /// - Returns: `[left, top, width, height]` constraints at `RRLayoutPriorityValue.required`.
    public static func framePinningConstraints(for view: UIView) -> [RRLayoutConstraint] {
        framePinningConstraints(
            forFrame: view.frame,
            autoresizingMask: view.autoresizingMask,
            firstItem: view,
            in: view.superview
        )
    }

    /// The four frame-pinning constraints for an explicit frame/mask pair (testable without a view).
    ///
    /// - Parameters:
    ///   - frame: the view's frame **in its superview's coordinate space**.
    ///   - autoresizingMask: the mask that produced the frame; recorded on the identifiers.
    ///   - firstItem: the item the constraints are installed on (the view itself).
    ///   - superview: the item position attributes are relative to; `nil` produces width/height only
    ///     for the position attributes' second item, matching `NSLayoutConstraint`'s single-item form.
    /// - Returns: `[left, top, width, height]` constraints at required priority when `superview` is
    ///   non-nil, or `[width, height]` when it is `nil` (a location attribute cannot be equal to a
    ///   constant).
    public static func framePinningConstraints(
        forFrame frame: CGRect,
        autoresizingMask: UIView.AutoresizingMask,
        firstItem: UIView,
        in superview: UIView?
    ) -> [RRLayoutConstraint] {
        let maskDescription = legacyAutoresizingMaskDescription(autoresizingMask)
        let identifier = "RRAutoLayoutAutoresizing:\(maskDescription)"

        var constraints: [RRLayoutConstraint] = []

        // Position constraints need a superview: a location attribute with a nil second item is an
        // illegal "location equal to a constant" constraint and UIKit raises for it.
        if let superview = superview {
            let leadingConstraint = RRLayoutConstraint(
                item: firstItem,
                attribute: .left,
                relatedBy: .equal,
                toItem: superview,
                attribute: .left,
                multiplier: 1,
                constant: frame.origin.x
            )
            let topConstraint = RRLayoutConstraint(
                item: firstItem,
                attribute: .top,
                relatedBy: .equal,
                toItem: superview,
                attribute: .top,
                multiplier: 1,
                constant: frame.origin.y
            )
            constraints.append(leadingConstraint)
            constraints.append(topConstraint)
        }

        let widthConstraint = RRLayoutConstraint(
            item: firstItem,
            attribute: .width,
            relatedBy: .equal,
            toItem: nil,
            attribute: .notAnAttribute,
            multiplier: 1,
            constant: frame.size.width
        )
        let heightConstraint = RRLayoutConstraint(
            item: firstItem,
            attribute: .height,
            relatedBy: .equal,
            toItem: nil,
            attribute: .notAnAttribute,
            multiplier: 1,
            constant: frame.size.height
        )
        constraints.append(widthConstraint)
        constraints.append(heightConstraint)

        for constraint in constraints {
            constraint.priority = RRLayoutPriorityValue.required
            constraint.identifier = identifier
        }
        return constraints
    }

    /// Human-readable mask, used in the generated constraints' identifiers (this is the "mask" half of
    /// the translation; the frame is the numeric half).
    public static func legacyAutoresizingMaskDescription(_ mask: UIView.AutoresizingMask) -> String {
        var components: [String] = []
        if mask.contains(.flexibleLeftMargin) { components.append("flexibleLeftMargin") }
        if mask.contains(.flexibleWidth) { components.append("flexibleWidth") }
        if mask.contains(.flexibleRightMargin) { components.append("flexibleRightMargin") }
        if mask.contains(.flexibleTopMargin) { components.append("flexibleTopMargin") }
        if mask.contains(.flexibleHeight) { components.append("flexibleHeight") }
        if mask.contains(.flexibleBottomMargin) { components.append("flexibleBottomMargin") }
        return components.joined(separator: "|")
    }
}
